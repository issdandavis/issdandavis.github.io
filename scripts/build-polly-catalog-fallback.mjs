// Browser-local copy for initial routing and when the published JSON is unavailable.
import { readFileSync, writeFileSync } from 'node:fs';

const file = (name) => new URL('../' + name, import.meta.url);
const source = (name) => JSON.parse(readFileSync(file(name), 'utf8'));
const target = file('static/polly-catalog-fallback.js');
const contents = '// Generated by scripts/build-polly-catalog-fallback.mjs. Do not edit.\nwindow.__POLLY_CATALOG_FALLBACK__ = ' + JSON.stringify({
  routing: source('assistant-routing.json'),
  catalog: source('assistant-catalog.json')
}) + ';\n';

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== contents) {
    console.error('Polly fallback differs from the route map or catalog. Regenerate it with node scripts/build-polly-catalog-fallback.mjs.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, contents);
}
